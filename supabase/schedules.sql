end;
$$;

-- 3-4. 削除
create or replace function public.delete_schedule(schedule_id bigint, key text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if key <> 'REPLACE_WITH_YOUR_PASSPHRASE' then
    raise exception '合言葉が間違っています';
  end if;

  delete from public.schedules where id = schedule_id;
end;
$$;

-- 4. 実行権限の付与
