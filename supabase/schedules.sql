-- ⚠️ 実行前に必ず、このファイル内の
--     'REPLACE_WITH_YOUR_PASSPHRASE'
--    を、実際に使っている「合言葉」に置き換えてください。
--    posts の管理画面と同じ合言葉にすれば、管理者は
--    同じ合言葉で記事投稿とスケジュール管理の両方を操作できます。
