    title = p_title,
    title_en = p_title_en,
    title_kr = p_title_kr,
    title_tr = p_title_tr,
    title_de = p_title_de,
    rule_label = p_rule_label,
    tag_color = p_tag_color,
    image_url = p_image_url,
